# Render the generated arrival region from the deed and STATE descriptile.
set -euo pipefail
root="${1:-$(git rev-parse --show-toplevel)}"
reader="$root/scripts/deed-field.sh"
deed="$(bash "$reader" --find "$root")"
state="$root/.machine_readable/descriptiles/STATE.deed"
[ -r "$state" ] || { echo "missing STATE.deed" >&2; exit 1; }
name="$(bash "$reader" "$deed" '' canonical-name)"
purpose="$(bash "$reader" "$deed" ecosystem purpose)"
chain="$(bash "$reader" "$deed" ecosystem chain)"
clade="$(bash "$reader" "$deed" clade rationale)"
phase="$(bash "$reader" "$state" status phase)"
maturity="$(bash "$reader" "$state" maturity level)"
commands="$(bash "$reader" --list "$deed" anchor/golden-path smoke-test-command)"
hash="$(cat "$deed" "$state" | sha256sum | cut -c1-12)"
cat <<END
<!-- ARRIVAL-PACK:BEGIN — deed and STATE @$hash — generated by just claude-md -->

# Orient before acting

Read \`0-AI-MANIFEST.deed\` and \`vocarium_chora.deed\`, then README.adoc and
AFFIRMATION.adoc. Read the estate standing rules before acting. Do not treat
unexecuted checks as passing; avoid silent skips and report evidence and limits.
Licence edits, release claims and destructive actions require appropriate review.

## This repo: $name

- Purpose: $purpose.
- Ecosystem: $chain.
- Clade: $clade
- Status: $phase; maturity: $maturity.
- State, metadata and agent constraints: \`.machine_readable/descriptiles/\`.
- Golden path (run with dependencies installed):
END
while IFS= read -r cmd; do printf '  - `%s`\n' "$cmd"; done <<< "$commands"
printf '\n%s\n' '<!-- ARRIVAL-PACK:END -->'
